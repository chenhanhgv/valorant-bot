# ==========================================
# 繪圖練習：畫出最近五場的擊殺數
# ==========================================

import matplotlib.pyplot as plt

# 1. 準備「假數據」 (我們假裝這是從 API 抓來的)
# ==========================================
# 最近 5 場對戰
games = ['Game 1', 'Game 2', 'Game 3', 'Game 4', 'Game 5']
# 每一場的擊殺數 (Kills)
kills = [15, 22, 10, 18, 25]


# 2. 準備「雲端畫布」
# ==========================================
# 建立一個寬 8 吋、高 5 吋的畫布
plt.figure(figsize=(8, 5))


# 3. 開始繪製 (使用基礎長條圖 .bar)
# ==========================================
# 設定 X軸 為場次，Y軸 為擊殺數，並將顏色設為特戰英豪的「紅色」 (#FF4655)
plt.bar(games, kills, color='#FF4655')


# 4. 裝飾圖表 (加上標題和標籤)
# ==========================================
# 圖表大標題
plt.title('Recent 5 Games - Kills Performance', fontsize=16)
# X軸標籤
plt.xlabel('Match No.', fontsize=12)
# Y軸標籤
plt.ylabel('Kills', fontsize=12)


# 5. 生成圖片檔案
# ==========================================
# 這步最重要！把畫好的內容存成一張名為 'kills_chart.png' 的圖片
# 放在同一個資料夾裡
plt.savefig('kills_chart.png')

print("✅ 練習圖表生成成功！請檢查你的資料夾，尋找 'kills_chart.png' 檔案。")